package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "uso: aliasgen <domain-dir> <package-name> <output-file>")
		os.Exit(2)
	}
	dir, pkg, out := os.Args[1], os.Args[2], os.Args[3]
	types := map[string]bool{}
	consts := map[string]bool{}
	vars := map[string]bool{}
	funcs := map[string]bool{}
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		panic(err)
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, e.Name()), nil, 0)
		if err != nil {
			panic(err)
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						if s.Name.IsExported() {
							types[s.Name.Name] = true
						}
					case *ast.ValueSpec:
						for _, n := range s.Names {
							if !n.IsExported() {
								continue
							}
							if d.Tok == token.CONST {
								consts[n.Name] = true
							} else {
								vars[n.Name] = true
							}
						}
					}
				}
			case *ast.FuncDecl:
				if d.Recv == nil && d.Name.IsExported() {
					funcs[d.Name.Name] = true
				}
			}
		}
	}

	for n := range consts {
		if types[n] {
			delete(consts, n)
		}
	}
	for n := range vars {
		if types[n] || consts[n] {
			delete(vars, n)
		}
	}
	for n := range funcs {
		if types[n] || consts[n] || vars[n] {
			delete(funcs, n)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by aliasgen; DO NOT EDIT.\n\npackage %s\n\n", pkg)
	fmt.Fprintf(&b, "import dominio \"uniapp/internal/domain/%s\"\n\n", filepath.Base(dir))
	if len(types) > 0 {
		b.WriteString("type (\n")
		for _, n := range sorted(types) {
			fmt.Fprintf(&b, "\t%s = dominio.%s\n", n, n)
		}
		b.WriteString(")\n\n")
	}
	if len(consts) > 0 {
		b.WriteString("const (\n")
		for _, n := range sorted(consts) {
			fmt.Fprintf(&b, "\t%s = dominio.%s\n", n, n)
		}
		b.WriteString(")\n\n")
	}
	if len(vars) > 0 {
		b.WriteString("var (\n")
		for _, n := range sorted(vars) {
			fmt.Fprintf(&b, "\t%s = dominio.%s\n", n, n)
		}
		b.WriteString(")\n\n")
	}
	if len(funcs) > 0 {
		b.WriteString("var (\n")
		for _, n := range sorted(funcs) {
			fmt.Fprintf(&b, "\t%s = dominio.%s\n", n, n)
		}
		b.WriteString(")\n")
	}
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}

func sorted(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for n := range m {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}
